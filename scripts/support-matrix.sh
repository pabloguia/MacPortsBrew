# The published support matrix is generated from what CI actually runs
# (docs/spec/07-quality-and-testing.md; 08-distribution-and-project.md,
# "Compatibility posture"). "Tested" means a runner label in
# .github/workflows/repository-validation.yml executes the suite there;
# "best-effort" means the deployment floor is met and asserted mechanically
# but nothing executes there; "unsupported" is below the floor (ADR-0002).
#
#   scripts/support-matrix.sh           print the matrix
#   scripts/support-matrix.sh --check   fail if docs/support-matrix.md differs

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 1

python3 - "${1:-}" <<'PY'
import re
import subprocess, sys
wf = open(".github/workflows/repository-validation.yml", encoding="utf-8").read()
m = re.search(r"runner:\s*\[([^\]]*)\]", wf)
labels = [l.strip() for l in m.group(1).split(",")] if m else []
tested = set()
for l in labels:
    mm = re.match(r"macos-(\d+)(-intel)?$", l)
    if not mm: continue
    major = int(mm.group(1)); arch = "x86_64" if mm.group(2) else "arm64"
    tested.add((major, arch))
def status(major_minor, arch):
    major = major_minor[0]
    if arch == "x86_64" and major_minor < (10, 12): return "unsupported"
    if arch == "arm64" and major_minor < (11, 0): return "unsupported"
    if (major, arch) in tested: return "tested"
    return "best-effort"
versions = [(10,12),(10,13),(10,14),(10,15),(11,0),(12,0),(13,0),(14,0),(15,0),(26,0)]
names = {(10,12):"10.12 Sierra",(10,13):"10.13 High Sierra",(10,14):"10.14 Mojave",(10,15):"10.15 Catalina",(11,0):"11 Big Sur",(12,0):"12 Monterey",(13,0):"13 Ventura",(14,0):"14 Sonoma",(15,0):"15 Sequoia",(26,0):"26 Tahoe"}
out = []
out.append("<!-- Generated by scripts/support-matrix.sh from .github/workflows/repository-validation.yml. Do not edit by hand. -->")
out.append("# Support matrix")
out.append("")
out.append("What CI is configured to exercise versus what is merely believed to work")
out.append("(`docs/spec/08-distribution-and-project.md`, \"Compatibility posture\").")
out.append("The floor is macOS 10.12 on Intel and 11.0 on Apple Silicon (ADR-0002); it")
out.append("is asserted on every built artifact by `scripts/check-deployment-target.sh`.")
out.append("")
remotes = subprocess.run(
    ["git", "remote"], capture_output=True, text=True, check=False
).stdout.strip()
if not remotes:
    out.append("> **No CI job has ever run.** This repository has no git remote, so the")
    out.append("> workflow below has never been executed by a hosted runner. Every row in")
    out.append("> this table describes configuration. Claiming tested support for an")
    out.append("> untested OS is the kind of dishonesty this project cannot afford")
    out.append("> (`docs/spec/08-distribution-and-project.md`), and a table that reads as")
    out.append("> evidence while being generated from labels is how that claim gets made")
    out.append("> without anyone deciding to make it.")
    out.append("")
out.append("| macOS | Intel x86_64 | Apple Silicon arm64 |")
out.append("|---|---|---|")
for v in versions:
    out.append(f"| {names[v]} | {status(v, 'x86_64')} | {status(v, 'arm64')} |")
out.append("")
out.append("- **tested**: a hosted runner with that macOS major and architecture is")
out.append("  configured to run the full suite natively (`" + "`, `".join(labels) + "`).")
out.append("  Read that as configuration, not as evidence: this table is generated from")
out.append("  the workflow's `runner:` labels and from nothing else, so it says what CI")
out.append("  would run, not what any run reported.")
out.append("- **best-effort**: the deployment floor is met and checked on the artifacts,")
out.append("  and nothing executes there. macOS 10.12 to 10.15 have no hosted runner")
out.append("  under GitHub's image policy (`docs/research/R-10-ci-runners.md`,")
out.append("  read 2026-09-02); verification on real hardware is welcome.")
out.append("- **unsupported**: below the floor.")
out.append("")
text = "\n".join(out) + "\n"
def without_the_remote_notice(s):
    """Drop the "No CI job has ever run" block before comparing.

    That block is emitted only when `git remote` is empty, and emptiness is a
    property of *this checkout*, not of the repository. `actions/checkout`
    always configures `origin`, so the committed file - generated here, where
    there is no remote - can never equal what CI generates. Harmless while this
    was one workflow step; the moment F-45 made it a `validate.sh` stage it
    would have failed the gate in all five jobs on the first push, and locally
    the moment anyone ran `git remote add`.

    What this check exists for is the sentence above the table: the matrix is
    generated from the workflow's `runner:` labels and from nothing else. That
    is what is compared. Whether the notice belongs at all - CI not having run
    is a fact about the project, and a clone having a remote does not change it
    - is SE-052's question, and this does not answer it.
    """
    kept, blank = [], False
    for line in s.splitlines():
        if line.startswith(">"):
            continue
        # The notice block is followed by its own blank line, so dropping only
        # the quoted lines leaves the two versions differing by one newline.
        if not line.strip():
            if blank:
                continue
            blank = True
        else:
            blank = False
        kept.append(line)
    return "\n".join(kept).strip() + "\n"


if sys.argv[1] == "--check":
    try:
        current = open("docs/support-matrix.md", encoding="utf-8").read()
    except FileNotFoundError:
        current = ""
    if without_the_remote_notice(current) != without_the_remote_notice(text):
        sys.stderr.write("support-matrix: docs/support-matrix.md is out of date; run scripts/support-matrix.sh > docs/support-matrix.md\n")
        sys.exit(1)
    print("support-matrix: ok")
else:
    sys.stdout.write(text)
PY
